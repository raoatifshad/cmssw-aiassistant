GRAPH_SCHEMA = """
NODES:
    (:IB {ib_key, tag, release, arch, parent_tag, variant})
  (:Package {name})
  (:Warning {hash, file, line, message, flag, count, package})
  (:SourceFile {path})
  (:Checker {name})           — e.g. 'threadsafety.ConstCast', 'cms.FunctionChecker'
    (:PR {repo, number, title, body, merged_at, release, changed_files, additions, deletions, sha, labels})
    (:Issue {issue_key, repo, number, title, body, state, github_url, created_at, updated_at, closed_at, labels})
    (:GitHubComment {key, body, created_at, updated_at, author, source_id})
    (:Label {key, name})
  (:Author {name})
    (:RelVal {key, ib_key, ib_tag, arch, workflow_id, name, status, errors, warnings, exitcode})
    (:RelValException {key, ib_key, ib_tag, arch, workflow_id, step, category, message, context, text, source_url})
    (:ExitCode {code, name}) — static CMSSW exit-code table, e.g. 16640 -> 'OtherCMS'; not IB-scoped
    (:Concept {concept_id, question, definition, source_feedback_id, verification_method,
        status, expires_at, last_revalidated_at, created_at})
        — a correction that passed the same graph-evidence verification gate as an
        accepted UserFeedback row, stored as a durable fact. status is 'active' or
        'revoked'; an active Concept is periodically re-verified against current graph
        facts before expires_at (see ingestion/revalidate_feedback.py) and revoked if it
        no longer holds -- never trusted indefinitely from a single automated check, and
        never promoted by user agreement alone.
    (:AlertRule {rule_id, name, capability, params, condition, channel, owner, active, created_at})
    (:ShiftSummary {key, previous_tag, latest_tag, release, markdown, generated_at})
        — a cached virtual-shifter digest for one (previous_tag, latest_tag) pair,
        generated by generate_shift_summary() (server/api_server.py) and produced on
        a schedule by ingestion/generate_shift_summaries.py. markdown already carries
        every relevance-only caveat inline; do not re-summarize it as causal.
    (:UnitTest {key, ib_key, ib_tag, arch, name, status, errors, ok})
    (:DocChunk {id, source_id, source_path, heading, text, chunk_index})
        — a chunk of static CMSSW/CMSSDT shifter documentation (Jenkins job
        runbooks, release-cycle procedures), ingested once from a local
        clone of cms-sw/cmssdt-wiki and cmsrepo's own top-level docs, never
        fetched live. Background/procedural knowledge, not a fact about any
        specific IB -- searched via search_shifter_docs(), never query_graph
        directly (it's indexed by a fulltext index, not a property match).
    (:ImportState {source_id, content_hash, source_type, source_path, last_ingested_at})
    (:TestLogRun {key, ib_key, ib_tag, arch, suite, run_variant, queue, server_path, total, passed,
        failed, other, passed_tests, failed_tests, other_tests, failed_details, scanned_at})
        — one scanned test-log zip of one IB: suite is 'unit' (unitTestLogs.zip), 'addon'
        (addOnTests.zip) or 'relval' (pyRelValMatrixLogs.zip); run_variant is '' or e.g.
        'gpu/nvidia_t4', 'other/rntuple' (NOT the same as IB.variant). passed_tests etc. are
        lists of names: unit 'Package/Sub/testName', addon 'test:stepN', relval workflow
        folder '<number>_<name>'. Statuses come from the logs themselves.
    (:LogProblem {key, ib_key, ib_tag, arch, suite, run_variant, kind, category, severity, origin,
        serious, summary, message, evidence, signature_id, count, owners, owner_statuses,
        in_passed, in_failed, intentional_hint, example_member, example_line, server_path,
        modules, producers, names, context_keys, contexts})
        — one distinct problem found in one zip's logs. evidence is one example block;
        modules ("Type/'label'"), producers (module types, cfi plugin names, source types),
        names (every specific name), context_keys ("<category>|<producer>") and contexts
        (normalized "[N] ..." lines) come from every occurrence in that zip. kind: fatal_exception, sanitizer,
        ubsan, crash, assertion, uncaught_exception, python_traceback, infrastructure_error
        (serious=true), message_logger (grouped %MSG-w/e), generic_error_line. owners lists
        every test/workflow(:stepN) that hit it, owner_statuses their status (parallel list);
        in_passed=true means it appeared in a test the dashboard shows as PASSED. origin:
        cmssw, infrastructure or unclassified. server_path is the zip on cmssdt9-02,
        which deletes it after ~1 week. intentional_hint is text from the log near the
        problem suggesting it is deliberate -- a hint only, never proof.
        Full-text index logProblemText on [summary, text] for pasted exceptions.
    (:ProblemSignature {signature_id, kind, category, signature, summary, first_seen_tag,
        first_seen_when, last_seen_tag, last_seen_when})
        — the same normalized problem across all IBs (when = 'YYYY-MM-DD-HHMM' from the tag).
    (:ProblemFirstSeen {key, suite, series, owner, signature_id, first_seen_tag, first_seen_when, arch})
        — first IB in which a serious problem or generic error line appeared for one test, per
        release series (e.g. CMSSW_20_1; sub-IBs share their series).

EDGES:
  (IB)-[:REPORTED]->(Warning)
  (IB)-[:HAS_WARNING_IN]->(Package)
  (Warning)-[:IN_PACKAGE]->(Package)
  (Warning)-[:IN_FILE]->(SourceFile)
  (Warning)-[:CHECKED_BY]->(Checker)
  (Package)-[:CONTAINS]->(SourceFile)
  (SourceFile)-[:FLAGGED_BY]->(Checker)
  (IB)-[:RAN_RELVAL]->(RelVal)
  (IB)-[:RAN_UNITTEST]->(UnitTest)
  (UnitTest)-[:IN_PACKAGE]->(Package)
  (IB)-[:HAS_TEST_LOG]->(TestLogRun)
  (TestLogRun)-[:HAS_PROBLEM]->(LogProblem)
  (LogProblem)-[:HAS_SIGNATURE]->(ProblemSignature)
  (PR)-[:AUTHORED_BY]->(Author)
    (Issue)-[:AUTHORED_BY]->(Author)
    ((PR|Issue))-[:HAS_COMMENT]->(GitHubComment)
    ((PR|Issue))-[:HAS_LABEL]->(Label)
    ((PR|Issue))-[:REFERENCES {source:'github_body'}]->((PR|Issue))
    (GitHubComment)-[:REFERENCES {source:'github_comment'}]->((PR|Issue))
    (PR)-[:MERGED_BEFORE]->(IB)
        — this PR was newly merged as of this IB build (the same "recently merged"
        list the CMSSDT dashboard shows per tag). Sourced from cms-sw.github.io's
        merged_prs_summary.json (ingest_merged_prs); a PR only attaches if it's
        already imported and the target tag matches an already-imported IB.
    (PR)-[:CHANGED_FILE {evidence:'github_changed_file'}]->(SourceFile)
    (PR)-[:MATCHES_WARNING {evidence:'changed_file'}]->(Warning)

MATCHES_WARNING means a PR changed the warning's source file. It is a
potential attribution signal, not proof that the PR introduced the warning.
CHANGED_FILE and PR title matches are weaker discovery signals when no warning
edge is available; callers receive their evidence types explicitly.
PR descriptions are searchable as pr_description evidence.
GitHub REFERENCES edges represent an explicit #number or CMSSW GitHub URL in a
body or comment. They do not establish causality, a dependency, or a fix.
UnitTest results are package-level aggregates. A PR test-file match in a failed
package is evidence of relevance, not a failure for a specific test name.
An IB with no variant is a primary run. An IB with a variant (for example,
NONLTO or CLANG) is a sub-IB whose parent_tag identifies its primary run.
RelValException category/message/context come from EDM Fatal Exception text
in a cms-bot es-cmssw-exceptions.py Elasticsearch export (--es-exceptions-json;
the CMSSDT logreader itself requires CERN SSO, so exceptions are sourced from
ES instead). An exception only exists here if both its RelVal and its
release/architecture/workflow were present in that export -- coverage is
whatever the export covered, not automatically comprehensive. source_url
points at the run's log file with no line-range anchor, since ES stores a
structured field, not a byte offset into a real file.
RelValException has NO relationship to RelVal or IB -- match it directly by
its own ib_tag/arch/workflow_id properties (e.g. MATCH (e:RelValException
{workflow_id:$id}) WHERE e.ib_tag = $tag). A query that instead tries to
traverse from RelVal or IB to reach a RelValException will silently return
zero rows no matter how much real exception data is imported.
"""

MAX_ROWS = 100
_WRITE_KEYWORDS = re.compile(
    r"\b(MERGE|CREATE|DELETE|SET|REMOVE|DROP|DETACH|CALL\s+db\.)\b", re.IGNORECASE
)


def _enforce_read_only(cypher: str):
    if _WRITE_KEYWORDS.search(cypher):
        raise ValueError("Only read queries (MATCH/RETURN) are allowed.")


def _run_query(cypher: str, params: dict | None = None) -> list[dict]:
    _enforce_read_only(cypher)
    driver = get_driver()
    try:
        with driver.session() as s:
            result = s.run(cypher, params or {})
            records = [dict(r) for r in result]
            return records[:MAX_ROWS]
    finally:
        driver.close()


