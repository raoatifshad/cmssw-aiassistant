def get_failing_relvals(ib_tag: str, arch: str | None = None, limit: int = 50) -> list[dict]:
    """Failed RelVals for an IB, including sub-IBs when given a primary tag. Excludes
    known_error=true workflows (e.g. "Grid-packs missing asan and non-asan shared
    libraries") to match the real CMSDT dashboard's own failing count/list, which
    excludes them the same way - see ingestion/build_graph.py's _ingest_relval_file for
    where known_error is captured and the live discrepancy that prompted this.

    `limit` caps rows PER MATCHED IB NODE (via a correlated subquery), not globally
    across all of them, and this bypasses _run_query's own MAX_ROWS post-slice -
    otherwise a single heavily-failing sub-IB can consume the entire row budget and
    silently return zero rows for every OTHER variant, including the primary itself,
    even though it has real failures too. Found live (2026-09-09): given a primary
    tag, UBSAN alone had 948/955 RelVals failing; a flat "ORDER BY ib.tag ... LIMIT
    100" (ib.tag sorts UBSAN before the primary tag's own "..._X_..." string) meant
    the primary's own single failing workflow never made it into the result at all.
    generate_shift_summary's diff then saw an empty "before" set for primary and
    reported an already-failing workflow as brand new -- a false "newly failing"
    alert. Per-node limiting guarantees every variant present gets its own fair
    share of the cap instead of one variant starving the rest."""
    limit = min(limit, MAX_ROWS)
    driver = get_driver()
    try:
        with driver.session() as s:
            rows = [dict(r) for r in s.run(
                "MATCH (ib:IB) "
                "WHERE (ib.tag = $t OR ib.parent_tag = $t) AND ($arch IS NULL OR ib.arch = $arch) "
                "CALL (ib) { "
                "  MATCH (ib)-[:RAN_RELVAL]->(rv:RelVal {status:'FAILED'}) "
                "  WHERE coalesce(rv.known_error, false) = false "
                "  RETURN rv "
                "  ORDER BY rv.workflow_id "
                "  LIMIT $lim "
                "} "
                "OPTIONAL MATCH (rv)-[:HAS_EXCEPTION]->(exc:RelValException) "
                "WITH ib, rv, collect(DISTINCT exc.step) AS raw_steps "
                "RETURN ib.tag AS ib_tag, ib.variant AS variant, rv.name AS name, "
                "rv.workflow_id AS workflow_id, rv.errors AS errors, rv.exitcode AS exitcode, "
                "[s IN raw_steps WHERE s IS NOT NULL] AS steps "
                "ORDER BY ib.tag, rv.workflow_id",
                {"t": ib_tag, "arch": arch, "lim": limit},
            )]
    finally:
        driver.close()
    # A RelVal can have zero, one, or several linked RelValException rows (a workflow
    # can fail across more than one cmsRun step, or the exception export can simply
    # miss it entirely - see ingest_es_exceptions/_ingest_relval_exception_file). Reduce
    # to one stable, order-independent value per workflow so it's usable as part of a
    # dict/set key (see _diff_failing_relvals's (workflow_id, step, exitcode) match key)
    # - None when no exception data exists for this workflow at all, distinct from any
    # real step name.
    for row in rows:
        steps = sorted(set(row.pop("steps", []) or []))
        row["step"] = ",".join(steps) if steps else None
    return rows


def get_failing_unittests(
    ib_tag: str, arch: str | None = None, limit: int = 50, include_sub_ibs: bool = False,
) -> list[dict]:
    """Unit tests with status=FAILED for a given IB. include_sub_ibs=True also pulls
    in every sub-IB whose parent_tag equals ib_tag (same "primary tag expands to its
    sub-IBs" pattern as get_failing_relvals) -- off by default because some callers
    (e.g. server.api_server._failed_unittest_package_listing) already loop over each
    exact sub-IB tag themselves and would double-count sub-IB failures under both
    their own section and the primary's if this defaulted on.

    When include_sub_ibs=True, `limit` caps rows PER MATCHED IB NODE (via a
    correlated subquery) rather than globally, and this bypasses _run_query's own
    MAX_ROWS post-slice -- the identical fix get_failing_relvals needed, for the
    identical reason: a single heavily-failing sub-IB must not crowd out every
    other variant's rows (including the primary's) under one flat limit."""
    limit = min(limit, MAX_ROWS)
    if not include_sub_ibs:
        return _run_query(
            "MATCH (ib:IB {tag:$t})-[:RAN_UNITTEST]->(ut:UnitTest {status:'FAILED'}) "
            "WHERE $arch IS NULL OR ib.arch = $arch "
            "RETURN ut.name AS name, ut.errors AS errors, ut.ok AS ok "
            "LIMIT $lim",
            {"t": ib_tag, "arch": arch, "lim": limit},
        )
    driver = get_driver()
    try:
        with driver.session() as s:
            rows = [dict(r) for r in s.run(
                "MATCH (ib:IB) "
                "WHERE (ib.tag = $t OR ib.parent_tag = $t) AND ($arch IS NULL OR ib.arch = $arch) "
                "CALL (ib) { "
                "  MATCH (ib)-[:RAN_UNITTEST]->(ut:UnitTest {status:'FAILED'}) "
                "  RETURN ut "
                "  ORDER BY ut.name "
                "  LIMIT $lim "
                "} "
                "RETURN ib.tag AS ib_tag, ib.variant AS variant, ut.name AS name, ut.errors AS errors, ut.ok AS ok "
                "ORDER BY ib.tag, ut.name",
                {"t": ib_tag, "arch": arch, "lim": limit},
            )]
    finally:
        driver.close()
    return rows


_UNIT_PROBLEM_KIND_RANK = {kind: rank for rank, kind in enumerate((
    "fatal_exception", "uncaught_exception", "crash", "sanitizer", "ubsan", "assertion",
    "python_traceback", "infrastructure_error", "message_logger", "generic_error_line"))}
_UNIT_PROBLEM_SEVERITY_RANK = {"fatal": 0, "error": 1, "system": 2, "warning": 3}


def get_unittest_log_details(builds: list[tuple[str, str]]) -> dict[tuple[str, str], dict]:
    """For each (IB tag, arch) -- a sub-IB by its own tag -- what the imported raw
    unit-test logs say: `imported` (any unit TestLogRun), `failed_tests` (full
    "Pkg/Sub/test" names, union over every unit run of that build: CPU and each GPU
    type) and `problems` ({test: (kind, message)}): for each failed test the most
    serious LogProblem with in_failed=true that names it as an owner whose own
    status is not "passed" -- never another test's error. Empty `problems` when the
    log has nothing for a failed test (e.g. CMSSW_20_1_ASAN_X_2026-10-05-2300
    Alignment/OfflineValidation: PrimaryVertex and testPVPlotting failed, no problem)."""
    keys = sorted({f"{tag}:{arch}" for tag, arch in builds if tag and arch})
    out = {(tag, arch): dict(imported=False, failed_tests=[], problems={}) for tag, arch in builds}
    if not keys:
        return out
    driver = get_driver()
    try:
        with driver.session() as session:
            for row in session.run(
                "MATCH (r:TestLogRun {suite:'unit'}) WHERE r.ib_key IN $keys "
                "RETURN r.ib_tag AS tag, r.arch AS arch, r.failed_tests AS failed ORDER BY r.key",
                keys=keys,
            ):
                entry = out.setdefault((row["tag"], row["arch"]), dict(imported=False, failed_tests=[], problems={}))
                entry["imported"] = True
                entry["failed_tests"] = list(dict.fromkeys(entry["failed_tests"] + list(row["failed"] or [])))
            best: dict[tuple, tuple] = {}
            for row in session.run(
                "MATCH (r:TestLogRun {suite:'unit'})-[:HAS_PROBLEM]->(p:LogProblem) "
                "WHERE r.ib_key IN $keys AND p.in_failed AND size(r.failed_tests) > 0 "
                "AND any(o IN p.owners WHERE o IN r.failed_tests) "
                "RETURN r.ib_tag AS tag, r.arch AS arch, r.failed_tests AS failed, p.owners AS owners, "
                "p.owner_statuses AS statuses, coalesce(p.serious, false) AS serious, p.kind AS kind, "
                "p.severity AS severity, coalesce(p.count, 0) AS count, p.message AS message, p.summary AS summary",
                keys=keys,
            ):
                text = row["message"] or row["summary"]
                if not text:
                    continue
                rank = (not row["serious"], _UNIT_PROBLEM_KIND_RANK.get(row["kind"], 99),
                        _UNIT_PROBLEM_SEVERITY_RANK.get(row["severity"], 9), -row["count"])
                statuses = row["statuses"] or []
                for i, owner in enumerate(row["owners"] or []):
                    if owner not in row["failed"] or (i < len(statuses) and statuses[i] == "passed"):
                        continue
                    key = (row["tag"], row["arch"], owner)
                    if key not in best or rank < best[key][0]:
                        best[key] = (rank, row["kind"], text)
    finally:
        driver.close()
    for (tag, arch, owner), (_, kind, text) in best.items():
        out.setdefault((tag, arch), dict(imported=True, failed_tests=[], problems={}))["problems"][owner] = (kind, text)
    return out


def get_unittest_recurrence(packages: list[str], arch: str) -> dict[tuple[str, str], list[tuple[str, str]]]:
    """Every imported result of these unit-test packages on one architecture, keyed
    by (package, variant) -- variant "" for the primary IB -- as [(tag, status)]
    newest first. Same idea as get_relval_recurrence, matched on package + variant +
    arch (a package failing on ASAN says nothing about the primary build)."""
    if not packages:
        return {}
    driver = get_driver()
    try:
        with driver.session() as session:
            rows = [dict(r) for r in session.run(
                "MATCH (u:UnitTest) WHERE u.arch = $arch AND u.name IN $packages "
                "MATCH (ib:IB {ib_key: u.ib_key}) "
                "RETURN u.name AS name, coalesce(ib.variant, '') AS variant, ib.tag AS tag, u.status AS status",
                arch=arch, packages=sorted(set(packages)),
            )]
    finally:
        driver.close()
    out: dict[tuple[str, str], list[tuple[str, str]]] = {}
    for row in sorted(rows, key=lambda r: r["tag"].rsplit("_X_", 1)[-1], reverse=True):
        out.setdefault((row["name"], row["variant"]), []).append((row["tag"], row["status"]))
    return out


