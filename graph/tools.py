def get_graph_schema() -> str:
    """Return the knowledge graph schema (node labels, properties, edge types).
    Call this before writing Cypher for query_graph."""
    return GRAPH_SCHEMA


def get_database_overview() -> dict:
    """Return live graph coverage, including node counts and newest RelVal IB records."""
    node_counts = _run_query(
        "MATCH (node) UNWIND labels(node) AS label "
        "RETURN label, count(*) AS count ORDER BY label"
    )
    latest_relval_records = _run_query(
        "MATCH (ib:IB)-[:RAN_RELVAL]->(relval:RelVal) "
        "WITH ib, count(relval) AS relval_total "
        "RETURN ib.tag AS tag, ib.parent_tag AS parent_tag, ib.arch AS arch, relval_total "
        "ORDER BY right(ib.tag, 15) DESC, tag, arch LIMIT 20"
    )
    architectures = _run_query(
        "MATCH (ib:IB)-[:RAN_RELVAL]->(:RelVal) "
        "RETURN DISTINCT ib.arch AS arch ORDER BY arch"
    )
    return {
        "node_counts": {row["label"]: row["count"] for row in node_counts},
        "latest_relval_records": latest_relval_records,
        "relval_architectures": [row["arch"] for row in architectures],
        "limits": {
            "relval_errors": "aggregate workflow counters, not detailed diagnostics",
            "unit_tests": "package aggregates, not individual test-case results",
            "github_evidence": "local textual or provenance evidence only; not causality",
        },
    }


_IB_TAG_SORT_PATTERN = re.compile(
    r"^CMSSW_(\d+)_(\d+)(?:_.+)?_X_(\d{4}-\d{2}-\d{2}-\d{4})$"
)


def _ib_sort_key(tag: str) -> tuple:
    """Rank by release series (major, minor) first, then by build timestamp.

    A higher release series (e.g. 20_1) is "later" than a lower one (e.g. 20_0)
    even if that series' most recent build is older in wall-clock time — this
    matches how the IB dashboard orders releases.
    """
    match = _IB_TAG_SORT_PATTERN.match(tag)
    if not match:
        return (-1, -1, tag)
    major, minor, timestamp = match.groups()
    return (int(major), int(minor), timestamp)


def list_ib_tags(release: str | None = None, arch: str | None = None, limit: int = 20) -> list[dict]:
    """List known IB tags, most recent release series first, newest build within a series first."""
    limit = min(limit, MAX_ROWS)
    cypher = (
        "MATCH (ib:IB) WHERE ($rel IS NULL OR ib.release = $rel) "
        "AND ($arch IS NULL OR ib.arch = $arch) "
        "RETURN ib.tag AS tag, ib.arch AS arch, ib.release AS release"
    )
    # Fetch unsliced: _run_query truncates to MAX_ROWS before we can sort, which
    # would drop the actual top entries when there are more IBs than MAX_ROWS.
    driver = get_driver()
    try:
        with driver.session() as s:
            rows = [dict(r) for r in s.run(cypher, {"rel": release, "arch": arch})]
    finally:
        driver.close()
    rows.sort(key=lambda row: _ib_sort_key(row["tag"]), reverse=True)
    return rows[:limit]


_CONCEPT_STOPWORDS = {
    "what", "this", "that", "have", "does", "with", "from", "about", "which",
    "there", "would", "could", "should", "your", "when", "where", "will",
}


def search_concepts(question: str, limit: int = 5) -> list[dict]:
    """Search stored expert-corrected facts (:Concept) for ones relevant to a
    question. These are corrections that already passed the same verification
    gate as an accepted UserFeedback row -- durable graph facts, not just
    conversation history."""
    limit = min(limit, MAX_ROWS)
    terms = [
        word for word in re.findall(r"[A-Za-z][A-Za-z0-9_]{3,}", question)
        if word.lower() not in _CONCEPT_STOPWORDS
    ]
    if not terms:
        return []
    return _run_query(
        "MATCH (c:Concept) WHERE coalesce(c.status, 'active') = 'active' "
        "WITH c, [term IN $terms WHERE toLower(c.question) CONTAINS toLower(term) "
        "OR toLower(c.definition) CONTAINS toLower(term)] AS matched_terms "
        "WHERE size(matched_terms) > 0 "
        "RETURN c.question AS question, c.definition AS definition, "
        "size(matched_terms) AS match_count "
        "ORDER BY match_count DESC, c.created_at DESC LIMIT $limit",
        {"terms": terms, "limit": limit},
    )


def get_relval_recurrence(workflow_id: str) -> dict:
    """How often has this workflow failed across every imported IB, not just
    the one currently being discussed? Computed at query time from data
    already ingested -- no scheduled job needed, always current.

    A workflow_id is not a stable identity across CMSSW eras -- the same
    number can be reassigned to a physically different workflow (a different
    step composition, hence a different relval.name) when a later release
    series' matrix changes what runs in that slot. Found live: workflow_id
    "537.0" has 237 occurrences named "DYToLL012Jets_5FS_..." and a separate
    5 occurrences named "DYToLL012Jets_5FS_...+...+HARVESTGEN" from an
    unrelated, much older era. A naive `RETURN relval.name, count(relval),
    ...` with no explicit GROUP BY implicitly groups by every non-aggregated
    column including `name`, so it silently produces one row per distinct
    name and reading the first row (the old behavior here) picked between
    two unrelated workflows arbitrarily -- observed switching which one won
    across a plain database restart, with no code change at all. Scoped
    instead to the single most recent occurrence's name, so the answer is
    always about the workflow slot as it exists in current data, never an
    unpredictable blend of two workflows that happen to share a number.

    failed_records (each {"tag", "arch", "variant"}, "primary" for a non-sub-IB
    build) is sorted by _ib_sort_key (release series, then build timestamp)
    rather than a flat ib.tag string sort -- a sub-IB's tag (e.g.
    CMSSW_20_1_UBSAN_X_...) always sorts alphabetically BEFORE its primary's
    tag (CMSSW_20_1_X_...) purely because every variant name starts with a
    letter earlier than "X", regardless of actual date. A flat tag-string
    sort therefore systematically crowds every sub-IB failure out of a
    count-capped "most recent" list whenever the primary alone has enough
    failing architectures to fill the cap. Found live, workflow 537.0: real
    UBSAN/ROOT6 sub-IB failures existed in the graph but never appeared in
    the old flat top-10, which showed only primary-build duplicates (the
    same tag repeated once per failing architecture) with no way to tell
    them apart either -- variant/arch are now explicit per record instead of
    a bare, ambiguous tag string. failed_tags (bare tag strings, same
    corrected order) is kept for existing callers that only need the tag.

    Fetches every raw (name, status, known_error, tag, arch, variant) row
    directly (not via _run_query, whose MAX_ROWS row-count cap would
    otherwise truncate a heavily-recurring workflow's row set before this
    function can even determine which name is current) -- same bypass
    pattern get_failing_relvals/list_ib_tags already use, for the same
    reason.

    known_error=true rows (e.g. "Architecture incompatibility, GridPacks
    were built for x86_64" on an aarch64 architecture) are excluded from
    failed_appearances/failed_records, same as get_failing_relvals and every
    other failing-RelVal count in this codebase -- they represent a known,
    benign environmental limitation, not a real regression, matching the
    real CMSDT dashboard's own exclusion (see the "known_error RelVal
    exclusion" note elsewhere in this file). Found live: workflow 537.0's
    entire ROOT6 sub-IB failure history on el9_aarch64_gcc14 was
    known_error=true (GridPacks only built for x86_64) -- before this
    exclusion, a "recurring failure" answer misrepresented a well-understood
    architecture limitation as an unresolved regression, and it crowded a
    genuine ASAN/UBSAN sub-IB failure out of the capped list. total_appearances
    still counts every run regardless of known_error (failed + passed +
    known_error == total, same invariant used everywhere else);
    known_error_appearances is reported separately within the current name's
    scope so nothing is silently dropped without acknowledgment."""
    driver = get_driver()
    try:
        with driver.session() as s:
            rows = [dict(r) for r in s.run(
                "MATCH (ib:IB)-[:RAN_RELVAL]->(relval:RelVal {workflow_id:$workflow_id}) "
                "RETURN relval.name AS name, relval.status AS status, "
                "coalesce(relval.known_error, false) AS known_error, relval.exitcode AS exitcode, "
                "ib.tag AS tag, ib.arch AS arch, coalesce(ib.variant, 'primary') AS variant",
                {"workflow_id": workflow_id},
            )]
    finally:
        driver.close()
    if not rows:
        return {"workflow_id": workflow_id, "total_appearances": 0}
    current_name = max(rows, key=lambda r: _ib_sort_key(r["tag"]))["name"]
    current = [r for r in rows if r["name"] == current_name]
    genuine_failures = [r for r in current if r["status"] == "FAILED" and not r["known_error"]]
    known_error_failures = [r for r in current if r["status"] == "FAILED" and r["known_error"]]
    failed_records = sorted(genuine_failures, key=lambda r: _ib_sort_key(r["tag"]), reverse=True)[:10]
    return {
        "workflow_id": workflow_id,
        "name": current_name,
        "total_appearances": len(current),
        "failed_appearances": len(genuine_failures),
        "known_error_appearances": len(known_error_failures),
        "failed_records": [
            {"tag": r["tag"], "arch": r["arch"], "variant": r["variant"]} for r in failed_records
        ],
        "failed_tags": [r["tag"] for r in failed_records],
        # every genuine failure (uncapped), with exit code: the shift digest counts prior
        # failures within one (variant, arch) track, which the top-10 above can miss
        "failure_history": [
            {"tag": r["tag"], "arch": r["arch"], "variant": r["variant"], "exitcode": r.get("exitcode")}
            for r in sorted(genuine_failures, key=lambda r: _ib_sort_key(r["tag"]), reverse=True)
        ],
    }


def diff_warnings(before_tag: str, after_tag: str, arch: str, limit: int = 10) -> dict:
    """Diff Warning nodes between two IB(tag, arch) pairs by content hash.
    Returns {"new": [...], "resolved": [...], "changed": [...]}, each row
    capped at `limit` -- the same three Cypher shapes
    _clang_warning_comparison_answer used inline, extracted so the shift-
    summary generator can reuse them without re-deriving the Cypher."""
    limit = min(limit, MAX_ROWS)
    new = _run_query(
        "MATCH (after:IB {tag:$after_tag, arch:$arch})-[:REPORTED]->(warning:Warning) "
        "WHERE NOT EXISTS { "
        "  MATCH (:IB {tag:$before_tag, arch:$arch})-[:REPORTED]->(:Warning {hash:warning.hash}) "
        "} "
        "RETURN warning.file AS file, warning.line AS line, warning.flag AS flag, "
        "warning.message AS message, warning.count AS occurrences "
        "ORDER BY occurrences DESC, file, line LIMIT $limit",
        {"before_tag": before_tag, "after_tag": after_tag, "arch": arch, "limit": limit},
    )
    resolved = _run_query(
        "MATCH (before:IB {tag:$before_tag, arch:$arch})-[:REPORTED]->(warning:Warning) "
        "WHERE NOT EXISTS { "
        "  MATCH (:IB {tag:$after_tag, arch:$arch})-[:REPORTED]->(:Warning {hash:warning.hash}) "
        "} "
        "RETURN warning.file AS file, warning.line AS line, warning.flag AS flag, "
        "warning.message AS message, warning.count AS occurrences "
        "ORDER BY occurrences DESC, file, line LIMIT $limit",
        {"before_tag": before_tag, "after_tag": after_tag, "arch": arch, "limit": limit},
    )
    changed = _run_query(
        "MATCH (before:IB {tag:$before_tag, arch:$arch})-[:REPORTED]->(before_warning:Warning) "
        "MATCH (after:IB {tag:$after_tag, arch:$arch})-[:REPORTED]->(after_warning:Warning) "
        "WHERE before_warning.hash = after_warning.hash AND before_warning.count <> after_warning.count "
        "RETURN after_warning.file AS file, after_warning.line AS line, after_warning.flag AS flag, "
        "after_warning.message AS message, before_warning.count AS before_count, "
        "after_warning.count AS after_count "
        "ORDER BY abs(after_warning.count - before_warning.count) DESC, file, line LIMIT $limit",
        {"before_tag": before_tag, "after_tag": after_tag, "arch": arch, "limit": limit},
    )
    return {"new": new, "resolved": resolved, "changed": changed}


def get_shift_summary(previous_tag: str, latest_tag: str) -> dict | None:
    """Return a cached virtual-shifter digest for this exact tag pair, if
    generate_shift_summaries.py (or a live chat request) already produced
    one. None if nothing has been generated yet for this pair."""
    rows = _run_query(
        "MATCH (s:ShiftSummary {key:$key}) "
        "RETURN s.previous_tag AS previous_tag, s.latest_tag AS latest_tag, "
        "s.markdown AS markdown, s.generated_at AS generated_at",
        {"key": f"{previous_tag}::{latest_tag}"},
    )
    return rows[0] if rows else None


def store_shift_summary(previous_tag: str, latest_tag: str, markdown: str) -> None:
    """Idempotent MERGE by (previous_tag, latest_tag) -- matches the
    codebase's ImportState hash-and-skip idiom (build_graph.py's
    source_needs_import/mark_source_imported) rather than a separate
    watermark/cursor table. Re-running with the same key overwrites the
    stored markdown (deliberate, e.g. after a generation-logic improvement)
    -- callers that want skip-if-exists behavior call get_shift_summary()
    first. Bypasses _run_query since MERGE/SET are write keywords it blocks
    by design; not added to the read-only TOOLS registry for the same
    reason create_rule/deactivate_rule (graph/alerts.py) aren't."""
    major_minor = re.match(r"^CMSSW_(\d+)_(\d+)_", latest_tag)
    release = f"CMSSW_{major_minor.group(1)}_{major_minor.group(2)}_X" if major_minor else None
    driver = get_driver()
    try:
        with driver.session() as session:
            session.run(
                "MERGE (s:ShiftSummary {key:$key}) "
                "SET s.previous_tag=$previous_tag, s.latest_tag=$latest_tag, "
                "s.release=$release, s.markdown=$markdown, s.generated_at=datetime()",
                key=f"{previous_tag}::{latest_tag}",
                previous_tag=previous_tag, latest_tag=latest_tag,
                release=release, markdown=markdown,
            )
    finally:
        driver.close()


def search_workflow_ids(prefix: str, limit: int = 15) -> list[dict]:
    """Distinct imported workflow IDs starting with `prefix` (e.g. "140."),
    for suggesting a match when an exact workflow ID isn't found or is
    written as a wildcard (e.g. "140.xx"). Complements get_relval_recurrence,
    which needs a real, exact workflow ID. Fetches one extra row over `limit`
    so the caller can tell whether the match set was truncated without a
    separate count query.

    Grouped by workflow_id alone, not (workflow_id, name): the same workflow
    ID can carry different recorded names across IBs (confirmed in real
    data), and a caller listing only the ID would otherwise show the same ID
    twice with no visible difference.
    """
    rows = _run_query(
        "MATCH (relval:RelVal) WHERE relval.workflow_id STARTS WITH $prefix "
        "WITH relval.workflow_id AS workflow_id, collect(relval.name)[0] AS name "
        "RETURN workflow_id, name ORDER BY workflow_id LIMIT $limit",
        {"prefix": prefix, "limit": limit + 1},
    )
    return rows


def _recency_cutoff(days: int | None) -> str | None:
    if days is None:
        return None
    return (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%d-%H%M")


def relval_failure_architectures(days: int | None = 7) -> list[str]:
    """Distinct architectures with at least one failed RelVal within the
    given recency window (or every imported IB if days is None). Used to
    decide whether an architecture choice is needed before running
    top_recurring_relval_failures -- IBs of different architectures are
    never silently merged into one answer without the user choosing that,
    same rule as the rest of this codebase's IB-identity handling."""
    rows = _run_query(
        "MATCH (ib:IB)-[:RAN_RELVAL]->(relval:RelVal {status:'FAILED'}) "
        "WHERE ($cutoff IS NULL OR right(ib.tag, 15) >= $cutoff) "
        "AND coalesce(relval.known_error, false) = false "
        "RETURN DISTINCT ib.arch AS arch ORDER BY arch",
        {"cutoff": _recency_cutoff(days)},
    )
    return [row["arch"] for row in rows]


def top_recurring_relval_failures(days: int | None = 7, limit: int = 10, arch: str | None = None) -> list[dict]:
    """Rank workflows by how often they've failed across imported IBs,
    scoped to builds from the last `days` days (by IB tag timestamp), or
    every imported IB if days is None, and to one architecture if given.
    Complements get_relval_recurrence, which answers the single-workflow
    version of the same question -- this one answers "which workflows fail
    a lot" when no workflow is named yet.

    Time filtering reuses the fixed-width `YYYY-MM-DD-HHMM` suffix every IB
    tag ends in, which already sorts correctly as a plain string elsewhere
    in this codebase (e.g. _IB_TAG_SORT_PATTERN) -- no APOC dependency
    needed for a Cypher-side cutoff comparison.
    """
    limit = min(limit, MAX_ROWS)
    return _run_query(
        "MATCH (ib:IB)-[:RAN_RELVAL]->(relval:RelVal) "
        "WHERE ($cutoff IS NULL OR right(ib.tag, 15) >= $cutoff) AND ($arch IS NULL OR ib.arch = $arch) "
        "WITH relval.workflow_id AS workflow_id, relval.name AS name, ib, relval "
        "WITH workflow_id, name, count(relval) AS total_appearances, "
        "sum(CASE WHEN relval.status = 'FAILED' THEN 1 ELSE 0 END) AS failed_appearances, "
        "[tag IN collect(CASE WHEN relval.status = 'FAILED' THEN ib.tag ELSE null END) "
        "WHERE tag IS NOT NULL] AS failed_tag_list "
        "WHERE failed_appearances > 0 "
        "RETURN workflow_id, name, total_appearances, failed_appearances, "
        "failed_tag_list[0..5] AS failed_tags "
        "ORDER BY failed_appearances DESC, total_appearances DESC LIMIT $limit",
        {"cutoff": _recency_cutoff(days), "limit": limit, "arch": arch},
    )


def get_exit_code_names() -> dict[int, str]:
    """Return the full CMSSW exit-code -> category-name table (e.g. 16640 ->
    'OtherCMS'), imported from cms-sw.github.io's exitcodes.json. Small static
    reference data — one query fetches the whole table rather than one lookup
    per row. Bypasses _run_query's MAX_ROWS cap: the table has ~160 entries,
    already over that cap, and silently dropping some would misreport exit
    codes as unknown rather than fail loudly.
    """
    driver = get_driver()
    try:
        with driver.session() as s:
            rows = [dict(r) for r in s.run("MATCH (code:ExitCode) RETURN code.code AS code, code.name AS name")]
    finally:
        driver.close()
    return {row["code"]: row["name"] for row in rows}


